import { normalizeFrontendDesignKind } from '@ecos-studio/shared'
import type { ProjectRouteContext } from './projectManifestRegistration'
import type { WorkspaceWizardInitialConfig } from './workspaceNavigation'

/** Rehydrate frontend inputs directly, without backend Synthesis/PDK defaults. */
export function frontendWorkspaceReconfigureConfig(
  values: Record<string, unknown>,
  workspacePath: string,
  project: ProjectRouteContext | null,
): WorkspaceWizardInitialConfig {
  const kind = normalizeFrontendDesignKind(values.frontend_design_kind)
  return {
    designTool: 'frontend',
    frontend_design_kind: kind,
    directory: workspacePath,
    lockWorkspaceDirectory: true,
    replaceExistingWorkspace: true,
    standaloneWorkspace: !project,
    parameters: {
      ...values,
      frontend_design_kind: kind,
      design: String(values.design ?? values.Design ?? ''),
      top_module: String(values.top_module ?? values['Top module'] ?? ''),
      clock: String(values.clock ?? values.Clock ?? ''),
      frequency_max: Number(values.frequency_max ?? values['Frequency max [MHz]'] ?? 100),
    },
    filelist: kind === 'generic_rtl' ? String(values.input_filelist ?? '') : '',
    origin_def: '',
    origin_verilog: '',
    rtl_list: [],
    pdk: '',
    pdk_root: '',
    project_context: project
      ? {
          mode: 'select',
          project_name:
            project.projectName ||
            project.projectRoot.split('/').filter(Boolean).pop() ||
            '',
          project_root: project.projectRoot,
          project_json_path: `${project.projectRoot}/project.json`,
        }
      : undefined,
  }
}

/** Decode only ECC-FE's generated source-list format, preserving its include directories. */
export function restoreGeneratedRtlSources(
  config: WorkspaceWizardInitialConfig,
  text: string,
): void {
  const lines = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
  if (lines.shift() !== '# Generated by ecc-fe from selected RTL files') {
    throw new Error(
      'The generated RTL filelist was modified. Select the RTL inputs again before updating this workspace.',
    )
  }
  const decode = (token: string): string => {
    if (/^[a-zA-Z0-9_@%+=:,./-]+$/.test(token)) return token
    if (/^'(?:[^']|'"'"')*'$/.test(token))
      return token.slice(1, -1).replace(/'"'"'/g, "'")
    throw new Error(
      'The generated RTL filelist has unsupported entries. Select the RTL inputs again before updating this workspace.',
    )
  }
  const includes = lines
    .filter((line) => line.startsWith('+incdir+'))
    .map((line) => decode(line.slice(8)))
  const sources = lines.filter((line) => !line.startsWith('+incdir+')).map(decode)
  const normalizedSources = sources.map((source) => source.replace(/\\/g, '/'))
  const parents = new Set(
    normalizedSources.map((source) => source.slice(0, source.lastIndexOf('/'))),
  )
  if (
    !sources.length ||
    normalizedSources.some(
      (source) => !/^(\/|[a-zA-Z]:\/)/.test(source) || !/\.(v|sv|vh|svh)$/i.test(source),
    ) ||
    includes.length !== parents.size ||
    includes.some((directory) => !parents.has(directory.replace(/\\/g, '/')))
  ) {
    throw new Error(
      'The generated RTL filelist was modified. Select the RTL inputs again before updating this workspace.',
    )
  }
  config.filelist = ''
  // The generated filelist is also persisted in parameters.json for ECC-FE.
  // Remove that stale reference when the replacement switches to explicit RTL
  // files; otherwise the runtime can continue reading the old workspace list.
  delete config.parameters?.input_filelist
  config.rtl_list = sources
}
